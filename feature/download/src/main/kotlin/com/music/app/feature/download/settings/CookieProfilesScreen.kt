/** The name a file of exported cookies is offered under. */
private const val ExportedCookiesName = "cookies.txt"

/**
 * Seal's cookie profiles: whether downloads read sites signed in, every site cookies are saved for - pressed, signed in to
 * again; selected, removed - and a new one generated by signing in on it, with how many cookies there are in all. The cookies
 * can be exported as the file yt-dlp reads, or cleared.
 */
data object CookieProfilesScreen : Screen {

    @Composable
    override fun Content() {
        val navigator = LocalNavigator.current
        val context = LocalContext.current
        val viewModel: CookiesViewModel = hiltViewModel()
        val browser: BrowserViewModel = hiltViewModel()
        val shields by browser.shieldsPreferences.collectAsStateWithLifecycle()
        val update = browser.shields::update
        val sites by viewModel.sites.collectAsStateWithLifecycle()
        val preferences by viewModel.preferences.collectAsStateWithLifecycle()
        val selection = rememberSelectionState()
        var isShowingHelp by remember { mutableStateOf(false) }
        var isClearing by remember { mutableStateOf(false) }
        var isRemoving by remember { mutableStateOf(false) }
        val exporter = rememberLauncherForActivityResult(ActivityResultContracts.CreateDocument("text/plain")) { uri ->
            uri?.let { viewModel.export(it) { exported -> context.toast(if (exported) R.string.downloads_settings_cookies_exported else R.string.downloads_settings_cookies_not_exported) } }
        }

        Column(modifier = Modifier.fillMaxSize()) {
            MusicTopAppBar(
                title = stringResource(R.string.downloads_settings_cookies_title),
                onNavigateBack = navigator::back,
                actions = listOf(
                    TopBarAction(stringResource(R.string.downloads_settings_cookies_help), MusicIcons.Help) { isShowingHelp = true },
                    TopBarAction(stringResource(R.string.downloads_settings_export_cookies), MusicIcons.Export, enabled = sites.isNotEmpty()) {
                        exporter.launch(ExportedCookiesName)
                    },
                    TopBarAction(stringResource(R.string.downloads_settings_clear_cookies), MusicIcons.DeleteForever, enabled = sites.isNotEmpty()) {
                        isClearing = true
                    },
                ),
                selection = selection.toTopBarSelection(
                    actions = listOf(
                        selection.selectAllAction(sites.map(CookieSite::domain)),
                        TopBarAction(stringResource(R.string.downloads_settings_remove_cookies), MusicIcons.Delete) { isRemoving = true },
                    ),
                    onMoreOptions = null,
                ),
            )
            SettingsList {
                SettingsChoiceItem(
                    title = stringResource(R.string.browser_shields_cookies),
                    options = listOf(
                        stringResource(R.string.browser_shields_cookies_cross_site),
                        stringResource(R.string.browser_shields_cookies_all),
                        stringResource(R.string.browser_shields_cookies_allow),
                    ),
                    selectedIndex = shields.cookies.ordinal,
                    defaultIndex = CookieBlockMode.CROSS_SITE.ordinal,
                    onSelect = { index -> update { it.copy(cookies = CookieBlockMode.entries[index]) } },
                    icon = MusicIcons.Cookie,
                )
                // As Seal's: nothing to read sites signed in with yet, it says how to have some instead.
                SettingsSwitchContainerItem(
                    title = stringResource(R.string.downloads_settings_use_cookies),
                    checked = preferences.usesCookies,
                    onCheckedChange = { uses ->
                        if (uses && sites.isEmpty()) isShowingHelp = true else viewModel.updatePreferences { it.copy(usesCookies = uses) }
                    },
                )
                sites.forEach { site ->
                    MusicListRow(
                        title = site.domain,
                        subtitle = pluralStringResource(R.plurals.downloads_settings_cookie_count, site.cookieCount, site.cookieCount),
                        selection = selection,
                        selectionKey = site.domain,
                        onClick = { navigator.go(BrowserScreen(page = "https://${site.domain}")) },
                        onOpenOptions = null,
                        cover = { Icon(MusicIcons.Language, contentDescription = null) },
                    )
                }
                SettingsActionItem(
                    title = stringResource(R.string.downloads_settings_generate_cookies),
                    icon = MusicIcons.Add,
                    // Signed in on the browser, as on any - its address bar is where the site is gone to.
                    onClick = { navigator.go(BrowserScreen()) },
                )
                SettingsSwitchItem(
                    title = stringResource(R.string.downloads_settings_ua_header),
                    summary = stringResource(R.string.downloads_settings_ua_header_summary),
                    icon = MusicIcons.Language,
                    checked = preferences.sendsUserAgent,
                    onCheckedChange = { sends -> viewModel.updatePreferences { it.copy(sendsUserAgent = sends) } },
                )
                HorizontalDivider()
                val cookieCount = sites.sumOf(CookieSite::cookieCount)
                SettingsNote(
                    stringResource(
                        R.string.downloads_settings_cookies_total,
                        pluralStringResource(R.plurals.downloads_settings_cookie_count, cookieCount, cookieCount),
                        pluralStringResource(R.plurals.downloads_settings_site_count, sites.size, sites.size),
                    ),
                )
            }
        }

        if (isShowingHelp) {
            val okLabel = stringResource(DesignSystemR.string.dialog_ok)
            MusicDialog(
                onDismissRequest = { isShowingHelp = false },
                title = stringResource(R.string.downloads_settings_cookies_help),
                icon = { Icon(MusicIcons.Help, contentDescription = null) },
                buttons = { actionButton(label = okLabel, onClick = { isShowingHelp = false }) },
            ) {
                Text(stringResource(R.string.downloads_settings_cookies_usage))
            }
        }

        if (isClearing) {
            MusicConfirmationDialog(
                title = stringResource(R.string.downloads_settings_clear_cookies),
                message = stringResource(R.string.downloads_settings_clear_cookies_message),
                confirmLabel = stringResource(R.string.downloads_settings_clear_cookies_confirm),
                successMessage = stringResource(R.string.download_cookies_cleared),
                failureMessage = stringResource(R.string.download_delete_failed),
                onDismiss = { isClearing = false },
                operation = { onFinished ->
                    viewModel.clear()
                    selection.clear()
                    onFinished(true)
                },
            )
        }

        if (isRemoving) {
            val removed = sites.filter { selection.isSelected(it.domain) }
            MusicConfirmationDialog(
                title = stringResource(R.string.downloads_settings_remove_cookies),
                message = pluralStringResource(R.plurals.downloads_settings_remove_cookies_message, removed.size, removed.size),
                confirmLabel = stringResource(R.string.downloads_settings_remove_cookies),
                successMessage = stringResource(R.string.downloads_settings_cookies_removed),
                failureMessage = stringResource(R.string.download_delete_failed),
                onDismiss = { isRemoving = false },
                operation = { onFinished ->
                    removed.forEach(viewModel::remove)
                    selection.clear()
                    onFinished(true)
                },
            )
        }
    }
}
